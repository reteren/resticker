//! Питание машины: работаем ли мы сейчас от батареи.
//!
//! Нужно ровно одному потребителю — ограничителю частоты кадров оверлея
//! (`Settings::battery_fps_limit`): от сети оверлей рисует по событиям, как и
//! рисовал, а на батарее частоту имеет смысл придержать.

use windows::Win32::System::Power::{GetSystemPowerStatus, SYSTEM_POWER_STATUS};

/// Значение `ACLineStatus`, означающее «питание от батареи»
/// (документация `SYSTEM_POWER_STATUS`: 0 — offline, 1 — online, 255 —
/// неизвестно).
const AC_OFFLINE: u8 = 0;

/// Работает ли машина от батареи прямо сейчас.
///
/// `false` на любой неопределённости: и когда система отвечает «неизвестно»
/// (255 — так отвечают стационарные машины и часть виртуалок), и когда вызов
/// не удался. Ошибиться в эту сторону дешевле: лишний раз НЕ придержать
/// частоту — значит просто рисовать как раньше, а лишний раз придержать на
/// настольной машине пользователь увидел бы как необъяснимую вялость.
pub fn on_battery() -> bool {
    let mut status = SYSTEM_POWER_STATUS::default();
    // SAFETY: `status` — валидный out-параметр на весь вызов; функция только
    // заполняет структуру.
    if unsafe { GetSystemPowerStatus(&mut status) }.is_err() {
        return false;
    }
    status.ACLineStatus == AC_OFFLINE
}

#[cfg(test)]
mod tests {
    use super::*;

    /// На живой машине вызов обязан отработать без паники и вернуть ответ,
    /// согласованный сам с собой: это единственное, что можно утверждать, не
    /// зная, ноутбук это или настольный компьютер.
    #[test]
    fn on_battery_answers_without_panicking() {
        let first = on_battery();
        let second = on_battery();
        assert_eq!(first, second, "два подряд опроса питания разошлись");
    }
}
