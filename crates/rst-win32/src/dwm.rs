//! Тонкая обёртка над DWM: единственное, что нужно наружу, — синхронизация
//! с композицией.

use windows::Win32::Graphics::Dwm::DwmFlush;

/// Дождаться границы кадра композитора (DWM).
///
/// Зачем: наша графика поверх ЧУЖОГО окна отставала от него на кадр при
/// перетаскивании (репорт пользователя 2026-08-21). Замер воркера-
/// исследователя показал источник: `Present(1)` блокирует ровно один период
/// кадра (около 16.7 мс на 60 Гц), а геометрию мы читаем ДО этого ожидания —
/// к моменту показа она устаревает на целый кадр.
///
/// Лечение — поменять местами такт и сэмпл: сначала дождаться границы
/// композиции здесь, затем прочитать живые границы окна, собрать кадр и
/// отдать его без ожидания (`PresentSync::Immediate`). Тогда между чтением
/// геометрии и показом остаются единицы миллисекунд вместо кадра.
///
/// Блокирует вызывающий поток не дольше одного периода композиции — ровно
/// столько же, сколько блокировал `Present(1)`, так что «лишним
/// пробуждением» (ADR-006) вызов не является: он заменяет ожидание, а не
/// добавляет новое. Ошибку игнорируем: без композитора (сессия без
/// десктопа) ждать нечего и незачем.
pub fn wait_for_composition() {
    // SAFETY: DwmFlush не принимает аргументов и безопасен с любого потока.
    let _ = unsafe { DwmFlush() };
}
